/** Synthetic raw byte source used only for truncation, work ceilings and original short-read cases. */
class EnvelopeTestReader final : public LoadFilter {
public:
	std::vector<uint8_t> input; ///< Explicit bytes; never generated by a native save handler.
	size_t position = 0, fragment; ///< Actual consumed offset and maximum raw read size.
	/** @param input Exact test stream. @param fragment Maximum original bytes returned in a raw read. */
	explicit EnvelopeTestReader(std::vector<uint8_t> input, size_t fragment = SIZE_MAX) : LoadFilter(nullptr), input(std::move(input)), fragment(fragment) {}
	/** @param buf Destination. @param len Capacity. @return Actual original bytes, possibly shorter than requested. */
	size_t Read(uint8_t *buf, size_t len) override
	{
		const size_t count = std::min({len, this->fragment, this->input.size() - this->position});
		std::copy_n(this->input.begin() + this->position, count, buf);
		this->position += count;
		return count;
	}
	/** Rewind only original raw bytes; no codec exists in this reader. */
	void Reset() override { this->position = 0; }
};

/** @param hex Literal independently specified lowercase hexadecimal. @return Exact bytes. */
inline std::vector<uint8_t> EnvelopeHex(std::string_view hex)
{
	std::vector<uint8_t> bytes;
	/** @param digit Original hexadecimal digit. @return Its four-bit value. */
	const auto nibble = [](char digit) { return digit <= '9' ? digit - '0' : digit - 'a' + 10; };
	for (size_t index = 0; index < hex.size(); index += 2) bytes.push_back(static_cast<uint8_t>((nibble(hex[index]) << 4) | nibble(hex[index + 1])));
	return bytes;
}

/** @param payload Explicit compressed bytes. @param tag Exact native compressor name. @param version Original unchanged test version. @return Complete original eight-byte envelope and payload. */
inline std::vector<uint8_t> EnvelopeStream(std::vector<uint8_t> payload, std::string_view tag = "OTTN", uint16_t version = 1)
{
	std::vector<uint8_t> input(tag.begin(), tag.end());
	input.insert(input.end(), {static_cast<uint8_t>(version >> 8), static_cast<uint8_t>(version), 0, 0});
	input.insert(input.end(), payload.begin(), payload.end());
	return input;
}

/** Build the actual network map reader through real native packet transfer.
 * @param input Original save bytes divided across received packet bodies.
 * @return Native PacketReader, ready to replay its received buffer without any path.
 */
inline std::shared_ptr<PacketReader> EnvelopeNetworkReader(std::span<const uint8_t> input)
{
	auto reader = std::make_shared<PacketReader>();
	NetworkSocketHandler socket; // Ordinary unbound native socket state; packet reads require its actual client-lifetime checks.
	// Small disjoint packet bodies exercise actual AddPacket/TransferOut, not a
	// vector reader labelled as network input. The original packet type is consumed first.
	while (!input.empty()) {
		Packet packet(&socket, PacketType{0});
		const auto count = std::min<size_t>(input.size(), 97);
		REQUIRE(packet.Send_bytes(input.first(count)).empty());
		packet.PrepareToSend();
		REQUIRE(packet.PrepareToRead());
		packet.Recv_uint8();
		reader->AddPacket(packet);
		input = input.subspan(count);
	}
	reader->Reset();
	return reader;
}

/** Replay through a new native codec after inspection, retaining no inspected decoder state.
 * @param raw Actual rewindable reader left at its original start by inspection.
 * @return Exact decoded original payload, bounded to one MiB for these small test inputs.
 */
inline std::vector<uint8_t> EnvelopeReplay(const std::shared_ptr<LoadFilter> &raw)
{
	raw->Reset();
	std::array<uint8_t, 8> header{};
	REQUIRE(raw->Read(header.data(), header.size()) == header.size());
	std::array<uint8_t, 4> tag{}; std::copy_n(header.begin(), 4, tag.begin());
	auto decoder = CreateSaveInspectionDecoder(raw, tag, (uint16_t{header[4]} << 8) | header[5]);
	std::array<uint8_t, 65536> block{};
	std::vector<uint8_t> result;
	// A new codec must decode the whole original, including complete trailers;
	// resetting only the old codec's chain would leave stale read-ahead state.
	while (const auto count = decoder->Read(block.data(), block.size())) {
		REQUIRE(result.size() + count <= 1048576);
		result.insert(result.end(), block.begin(), block.begin() + count);
	}
	return result;
}

/** @param digest Actual original SHA256. @return Lowercase hexadecimal for comparison to independent retained catalogues. */
inline std::string EnvelopeDigest(const std::array<uint8_t, 32> &digest)
{
	std::string hex;
	for (const auto byte : digest) { hex.push_back("0123456789abcdef"[byte >> 4]); hex.push_back("0123456789abcdef"[byte & 15]); }
	return hex;
}
