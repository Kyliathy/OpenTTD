"""Focused source-epoch reconstruction and unique-byte preservation checks.

@file artifact_source_epochs_check.py Protect authored sources before cleanup release.
@see docs/zz-reach2/upgrades/2026-10/r2fc2-file-cleanup3.md Group24 entry refresh of mutable original aliases.
@see docs/zz-reach2/upgrades/2026-10/r2fc-file-cleanup3.md Group9.4.
"""

import hashlib
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from artifact_paths import repository_root
from artifact_source_epochs import preserve_source_epochs, verify_source_epochs


class SourceEpochChecks(unittest.TestCase):
    """Exercise exact source provenance using repository-local synthetic epochs.

    @param self Active isolated test; no real snapshot or source is mutated.
    """

    def setUp(self):
        """Create an isolated scratch root and empty explicit candidate registry.

        @param self Active test instance.
        @return None; only the allocated scratch directory is removed at close.
        """
        cache = repository_root() / "test-cache/cleanup"
        cache.mkdir(parents=True, exist_ok=True)
        self.temporary = tempfile.TemporaryDirectory(dir=cache)
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.candidates = []

    def candidate(self, path, payload, disposition="preserve_source_epoch"):
        """Create one explicit source fixture row with independently hashed bytes.

        @param self Active isolated test.
        @param path Repository-relative synthetic source snapshot spelling.
        @param payload Exact fixture bytes, never generated by the tested helper.
        @param disposition Explicit generated classification or preservation duty.
        @return SHA256 of this independent fixture payload.
        """
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload)
        digest = hashlib.sha256(payload).hexdigest()
        self.candidates.append(dict(path=path, sha256=digest, bytes=len(payload), disposition=disposition))
        return digest

    def test_live_equivalent_and_unique_history_have_separate_roles(self):
        """Only exact live bytes reconstruct snapshots; differing old source is retained.

        @param self Active isolated test.
        @return None; duplicate historical aliases share one immutable source payload.
        """
        digest = self.candidate("logs/retained/current.cpp", b"// @see r2fc-file-cleanup3.md; current fixture.\n")
        live = self.root / "src/current.cpp"
        live.parent.mkdir(parents=True)
        live.write_bytes((self.root / "logs/retained/current.cpp").read_bytes())
        old_digest = self.candidate("logs/retained/old.cpp", b"// @see r2fc-file-cleanup3.md; prior fixture.\n")
        self.candidate("test-cache/prior/old.cpp", b"// @see r2fc-file-cleanup3.md; prior fixture.\n")
        result = preserve_source_epochs(self.candidates, self.root, {digest: dict(path="src/current.cpp", sha256=digest)})
        rows = {row["sha256"]: row for row in result["payloads"]}
        self.assertEqual(rows[digest]["disposition"], "reconstruct_from_identical_live_source")
        self.assertEqual(rows[old_digest]["disposition"], "retained_unique_historical_source")
        self.assertEqual(len(rows[old_digest]["original_paths"]), 2)
        with patch.object(Path, "mkdir", side_effect=AssertionError("verification writes")):
            self.assertEqual(verify_source_epochs(result, self.root), 2)

    def test_changed_mutable_original_reuses_only_its_exact_retained_epoch(self):
        """An ordinary rebuild cannot discard an already preserved older generated revision.

        @param self Isolated source-epoch refresh boundary test owner.
        """
        digest = self.candidate("build/generated/rev.cpp", b"// @see r2fc-file-cleanup3.md; old generated epoch.\n")
        result = preserve_source_epochs(self.candidates, self.root, {})
        (self.root / "build/generated/rev.cpp").write_bytes(b"// @see r2fc-file-cleanup3.md; newer generated epoch.\n")
        refreshed = preserve_source_epochs(self.candidates, self.root, {}, previous=result)
        self.assertEqual(refreshed["payloads"][0]["sha256"], digest)
        (self.root / result["payloads"][0]["reference"]["path"]).write_bytes(b"changed retained source")
        with self.assertRaisesRegex(ValueError, "without a verified retained copy"):
            preserve_source_epochs(self.candidates, self.root, {}, previous=result)

    def test_changed_live_source_requires_refresh_from_still_retained_original(self):
        """Later source edits cannot silently release the only matching old snapshot.

        @param self Active isolated test.
        @return None; refreshing exports exact old bytes before cleanup can proceed.
        """
        digest = self.candidate("logs/prior.cpp", b"// @see r2fc-file-cleanup3.md; immutable prior.\n")
        live = self.root / "src/current.cpp"
        live.parent.mkdir(parents=True)
        live.write_bytes((self.root / "logs/prior.cpp").read_bytes())
        result = preserve_source_epochs(self.candidates, self.root, {digest: dict(path="src/current.cpp", sha256=digest)})
        live.write_bytes(b"// @see r2fc-file-cleanup3.md; advanced live.\n")
        with self.assertRaisesRegex(ValueError, "refresh before cleanup"):
            verify_source_epochs(result, self.root)
        refreshed = preserve_source_epochs(self.candidates, self.root, {})
        self.assertEqual(refreshed["payloads"][0]["disposition"], "retained_unique_historical_source")

    def test_generated_filename_is_not_disposable_outside_build(self):
        """A name alone cannot classify an authored source template as generated.

        @param self Active isolated test.
        @return None; only the declared build copy is reconstructible output.
        """
        self.candidate("build/CPackConfig.cmake", b"# generated fixture\n")
        self.candidate("logs/authored/CPackConfig.cmake", b"# @see r2fc-file-cleanup3.md; authored fixture\n")
        result = preserve_source_epochs(self.candidates, self.root, {})
        self.assertEqual(len(result["generated"]), 1)
        self.assertEqual(len(result["payloads"]), 1)

    def test_consumed_native_source_inventory_survives_refresh_and_is_hash_checked(self):
        """Refresh retains the exact consumed source manifest and refuses its corruption.

        @param self Active isolated source/history owner.
        @return None; old native inventory paths stay facts, not rebuilt EXE dependencies.
        """
        self.candidate("logs/original.cpp", b"// @file original.cpp @see r2fc2-file-cleanup3.md; old source.\n")
        original = preserve_source_epochs(self.candidates, self.root, {})
        history = self.root / "src/tests/fixtures/cleanup/source-epochs/native-history.json"
        payload = json.dumps(dict(_documentation="r2fc2-file-cleanup3.md28 independent fixture", kind="native_source_epoch", files=[])).encode()
        history.write_bytes(payload)
        original["historical_native_epochs"] = [dict(path=history.relative_to(self.root).as_posix(), sha256=hashlib.sha256(payload).hexdigest())]
        refreshed = preserve_source_epochs(self.candidates, self.root, {}, previous=original)
        self.assertEqual(refreshed["historical_native_epochs"], original["historical_native_epochs"])
        history.write_bytes(payload + b"changed")
        with self.assertRaisesRegex(ValueError, "native source inventory changed"):
            verify_source_epochs(refreshed, self.root)


if __name__ == "__main__":
    unittest.main(verbosity=2)
