"""Actual subprocess fixture for recipe orchestration, without game/native work.

@file artifact_rebuild_fixture.py Test-only driver copied into isolated synthetic catalogues.
@see docs/zz-reach2/upgrades/2026-10/r2fc-file-cleanup3.md Group14.
The fixture checks independently supplied expected text, supports one intentional
verification failure, and never changes retained inputs or producer sources.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys


def identity(path, root):
    """Bind actual fixture bytes to the isolated checkout.

    @param path Explicit existing input/output/request.
    @param root Isolated source checkout.
    @return Exact path and SHA256 for actual test transport.
    """
    return dict(path=path.relative_to(root).as_posix(), sha256=hashlib.sha256(path.read_bytes()).hexdigest())


def validate_fixture_stage(request, root):
    """Provide a real independent text check to the production dispatcher unit test.

    @param request Explicit synthetic current-run verification request.
    @param root Isolated test checkout; all output paths were supplied by its executor.
    @return Measured checks, leaving production result publication to the actual dispatcher.
    """
    contract = json.loads((root / request["inputs"]["contract"]["path"]).read_text(encoding="utf-8"))
    actual = contract["value"].upper()
    if actual != contract["expected"]:
        raise ValueError("independent text expectation disagrees")
    (root / request["outputs"]["payload"]).write_text(actual, encoding="utf-8")
    (root / request["outputs"]["manifest"]).write_text(json.dumps(dict(actual=actual)), encoding="utf-8")
    return dict(checks=["actual text matched independently supplied expected value"])


def execute(path):
    """Perform a real bounded text conversion/check and publish the typed stage result.

    @param path Explicit request generated by the actual recipe executor.
    @return Actual child status; an intentional first failure writes no success result.
    """
    root = Path.cwd()
    request = json.loads(path.read_text(encoding="utf-8"))
    contract = json.loads((root / request["inputs"]["contract"]["path"]).read_text(encoding="utf-8"))
    if contract.get("no_op"):
        return 0
    payload = root / request["outputs"]["payload"]
    if request["stage"] == "prepare":
        payload.write_text(contract["value"].upper(), encoding="utf-8")
    if payload.read_text(encoding="utf-8") != contract["expected"]:
        raise ValueError("actual fixture text differs from independent expected text")
    prior = request["inputs"].get("prior-payload")
    if prior is not None:
        if (root / prior["path"]).read_text(encoding="utf-8") != contract["expected"]:
            raise ValueError("actual supplied prerequisite text disagrees")
    if request["stage"] == "verify":
        marker = path.parent / "intentional-failure-observed"
        # Exercise failure/resume without changing immutable input or source
        # hashes. Only the selected synthetic leaf fails once in its own run.
        if contract.get("fail_recipe") == request["recipe"] and not marker.exists():
            marker.write_text("Intentional fixture failure; @see r2fc-file-cleanup3.md14.\n", encoding="utf-8")
            return 7
        manifest = root / request["outputs"]["manifest"]
        manifest.write_text(json.dumps(dict(_documentation="Owner: r2fc-file-cleanup3.md14; synthetic text verification.",
            actual=payload.read_text(encoding="utf-8"), expected=contract["expected"])), encoding="utf-8")
    outputs = {role: identity(root / relative, root) for role, relative in request["outputs"].items()
               if (root / relative).is_file()}
    result = dict(_documentation="Owner: r2fc-file-cleanup3.md14; actual test-fixture stage checks.",
        schema_version=1, kind="artifact_recipe_stage_result", complete=True,
        recipe=request["recipe"], stage=request["stage"], run_id=request["run_id"], configuration=request["configuration"],
        request=identity(path, root), inputs=request["inputs"], sources=request["sources"], outputs=outputs,
        facts=dict(checks=["actual text matches independent expected value", "explicit predecessor text matches"]))
    (root / request["result_path"]).write_text(json.dumps(result), encoding="utf-8")
    return 0


def main():
    """Execute exactly the explicitly selected synthetic test request.

    @return Child status used by the real executor's failure/success state machine.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--request", required=True, type=Path)
    arguments = parser.parse_args()
    sys.exit(execute(arguments.request))


if __name__ == "__main__":
    main()
