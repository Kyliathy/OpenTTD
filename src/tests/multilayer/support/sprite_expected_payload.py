"""Bind original sprite expectation producers to explicit selected source packing.

@file sprite_expected_payload.py No native decoder, publication or old proof-cache fallback.
@see docs/zz-reach2/upgrades/2026-10/r2fc-file-cleanup3.md Groups18/18B/18C.
The existing producer catalogue supplies family/producer/scope assignments.
Independent pre-adaptation payload identities remain immutable regression facts.
"""

import argparse
import hashlib
import importlib
import json
from pathlib import Path
import sys

from artifact_paths import RunContext, contained, identifier, repository_root
from artifact_rebuild import identity
from artifact_recipes import load_catalogue, recipe_order

ROOT = repository_root()
FACTS = ROOT / "src/tests/fixtures/graphics/expected-sprite-facts.json"
FACTS_SHA256 = "fee40b874bcbe482577ca078eacc795fe20d6ff676f28c7aed149f1dc2aef9ba"


def load_facts():
    """Read independently preserved original payload identities without old binaries.

    @return Exact five-family regression facts; historical paths are never dereferenced.
    """
    if hashlib.sha256(FACTS.read_bytes()).hexdigest() != FACTS_SHA256:
        raise ValueError("independent original sprite expectation facts changed")
    return json.loads(FACTS.read_text(encoding="utf-8"))["families"]


def recipe_family(family):
    """Translate the original launch/fleet protocol label to its existing recipe prefix.

    @param family Exact original payload protocol family, including launch-fleet.
    @return Existing recipe family label; no asset identity or range is allocated.
    """
    if family not in load_facts():
        raise ValueError("unknown sprite expectation family")
    return "launch" if family == "launch-fleet" else family


def selected_path(reference, context, role):
    """Require exact current generated bytes from the explicitly selected invocation.

    @param reference Actual selected path/SHA256 identity supplied by a prerequisite.
    @param context Explicit consuming invocation; related scenarios retain separate owners.
    @param role Required data or reports role.
    @return Existing contained file with the exact supplied identity.
    """
    path = contained(context.root / reference["path"], context.root / "mlm/reviews")
    parts = path.relative_to(context.root / "mlm/reviews").parts
    # Related suppliers share an invocation, never yesterday's file location.
    # A current report cannot supply pixels or binary data through another role.
    if len(parts) != 5 or parts[2] != context.run_id or parts[3] != role:
        raise ValueError("sprite expectation input has a foreign invocation or role")
    if identity(path, context.root) != reference:
        raise ValueError("sprite expectation input identity changed")
    return path


def packing_inputs(family, reference, context):
    """Validate actual original packing reports and their exact current PNG/NFO/header.

    @param family Original binary protocol family selected by its recipe.
    @param reference Explicit actual packing report identity.
    @param context Selected current expectation output invocation.
    @return Checked report, current PNG path and existing original producer declaration.
    """
    name = recipe_family(family)
    recipes = {row["id"]: row for row in load_catalogue(context.root)["recipes"]}
    declaration = recipes[name + "-expected-payload"]
    packing = recipes[name + "-derived-inputs"]
    scope = json.loads((context.root / packing["original_parameters"]["scope"]).read_text(encoding="utf-8"))
    path = selected_path(reference, context, "reports")
    report = json.loads(path.read_text(encoding="utf-8"))
    expected = load_facts()[family]
    # Native ranges, route and runtime status belong to the existing source
    # contract. A different family's complete-looking report cannot supply it.
    if (report.get("route") != scope["native_route"] or report.get("native_sprite_bound") != expected["native_bound"]
            or report.get("runtime_activated") is not False):
        raise ValueError("sprite expectation packing family/range/status changed")
    if name != "m1":
        # M1's original selected report predates schema2, but its explicit
        # current file roles below still bind its writer and invocation.
        if report.get("kind") != "selected_" + name + "_packing" or report.get("run_id") != context.run_id:
            raise ValueError("sprite expectation packing family/invocation changed")
    references = [report[key] for key in ("png", "nfo", "header")] if name == "m1" else report["outputs"]
    outputs = {}
    # Every selected original artifact remains byte-exact against durable
    # shipping inputs; no generated actual becomes a replacement baseline.
    for role in ("png", "nfo", "header"):
        original = context.root / scope[role]
        matches = [row for row in references if Path(row["path"]).name == original.name]
        if len(matches) != 1:
            raise ValueError("sprite expectation packing output is missing or ambiguous")
        actual = selected_path({key: matches[0][key] for key in ("path", "sha256")}, context, "data")
        if actual.parent.parent != path.parent.parent:
            raise ValueError("sprite expectation packing has a foreign writer scenario")
        if hashlib.sha256(actual.read_bytes()).hexdigest() != hashlib.sha256(original.read_bytes()).hexdigest():
            raise ValueError("sprite expectation packing differs from original shipping bytes")
        outputs[role] = actual
    return report, outputs["png"], declaration


def checked_payload(family, reference, context):
    """Select an exact source-derived prefix payload through its typed current report.

    @param family Exact required original protocol family.
    @param reference Actual prerequisite expectation report identity.
    @param context Explicit consuming invocation sharing the original producer's run.
    @return Checked binary path; no old expected directory or decoder is consulted.
    """
    path = selected_path(reference, context, "reports")
    document = json.loads(path.read_text(encoding="utf-8"))
    name = recipe_family(family)
    declaration = next(row for row in load_catalogue(context.root)["recipes"] if row["id"] == name + "-expected-payload")
    expected = load_facts()[family]
    # A source expectation carries no native acceptance and cannot borrow
    # another family's data by changing a filename or reusing its run marker.
    if (document.get("kind") != "selected_sprite_expectations" or document.get("family") != family
            or document.get("run_id") != context.run_id or document.get("native_loading_verified") is not False
            or document.get("publishes_source") is not False or document.get("recipe") != declaration["id"]
            or document.get("producer") != identity(context.root / declaration["producer"], context.root)
            or document.get("comparison") != "independent_source_bytes"
            or document.get("configuration_reuse") != "source_bytes_only"
            or document.get("record_count") != expected["record_count"] or document.get("native_bound") != expected["native_bound"]):
        raise ValueError("sprite expectation prefix family/invocation/status changed")
    payload = selected_path(document["expected_payload"], context, "data")
    if payload.parent.parent != path.parent.parent:
        raise ValueError("sprite expectation prefix has a foreign writer scenario")
    # Preserved original identities predate all changed producers. Hashing the
    # actual selected prefix also catches coherent metadata/data replacements.
    if identity(payload, context.root)["sha256"] != expected["sha256"]:
        raise ValueError("sprite expectation prefix differs from independent original bytes")
    return payload


def produce(family, context, packing_reference, prefixes=None):
    """Execute the actual original source producer with explicit current inputs/output.

    @param family One existing original binary expectation family.
    @param context Exact current generated data/report owner, never an inferred latest run.
    @param packing_reference Actual selected original packing report identity.
    @param prefixes Exact family-to-current expectation report map for required predecessors.
    @return Actual source expectation facts and current report/payload identities.
    """
    if context.root.resolve() != ROOT:
        raise ValueError("sprite expectation producer belongs to another checkout")
    # Routing components remain plain identifiers; a caller cannot turn a
    # selected destination into another owner through crafted path components.
    for value in (context.feature, context.scenario, context.run_id):
        identifier(value)
    report, image, declaration = packing_inputs(family, packing_reference, context)
    required = {"m1", "space", "orbital"} if family == "launch-fleet" else {"launch-fleet"} if family == "ground" else set()
    prefixes = prefixes or {}
    if set(prefixes) != required:
        raise ValueError("sprite expectation requires its exact declared source prefix families")
    paths = {name: checked_payload(name, value, context) for name, value in prefixes.items()}
    producer = ROOT / declaration["producer"]
    sys.path.insert(0, str(producer.parent))
    module = importlib.import_module(producer.stem)
    destination = context.data / Path(next(row["path"] for row in declaration["outputs"] if row["role"] == "expected-payload")).name
    contained(destination, context.data)
    count = module.produce_selected(report, image, destination, prefixes=paths)
    actual = identity(destination, ROOT)
    expected = load_facts()[family]
    # The actual binary must reproduce independently preserved pre-edit bytes;
    # no successful source producer or current report may rebaseline this gate.
    if actual["sha256"] != expected["sha256"] or count != expected["record_count"]:
        raise ValueError("sprite expectation differs from independent original payload")
    packing_inputs(family, packing_reference, context)
    # Close generated prerequisites as well as the outer typed reports. A
    # producer cannot alter a selected source image or prefix binary and leave
    # its earlier manifest hash as apparent authority for successful completion.
    for name, reference in prefixes.items():
        checked_payload(name, reference, context)
    result = dict(_documentation=__doc__, schema_version=1, kind="selected_sprite_expectations",
        family=family, recipe=declaration["id"], run_id=context.run_id, expected_payload=actual,
        producer=identity(producer, ROOT), packing=packing_reference, prefixes=prefixes,
        record_count=count, native_bound=expected["native_bound"], comparison="independent_source_bytes",
        configuration_reuse="source_bytes_only", historical_expected=expected,
        native_loading_verified=False, publishes_source=False)
    output = context.reports / "derived.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return dict(manifest=identity(output, ROOT), expected_payload=actual, record_count=count,
        native_loading_verified=False, publishes_source=False,
        checks=["actual original source-expectation producer completed",
                "all payload bytes match independently preserved original expectations",
                "no native decoder, old proof cache or canonical publication used"])


def execute_stage(request, root):
    """Run one registered pure expectation leaf through the existing shared dispatcher.

    @param request Actual selected current prepare/verify request and prerequisite identities.
    @param root Exact checkout selected by the shared executor.
    @return Actual measured preparation or complete source expectation facts.
    """
    if root.resolve() != ROOT:
        raise ValueError("sprite expectation stage belongs to another checkout")
    family = request["declaration"]["original_parameters"]["family"]
    context = RunContext(root, request["feature"], request["scenario"], request["run_id"])
    name = recipe_family(family)
    reference = request["inputs"][name + "-derived-inputs"]
    packing_inputs(family, reference, context)
    if request["stage"] == "prepare":
        return dict(checks=["exact selected original packing/source/shipping identities verified"])
    prefixes = {key.removesuffix("-prefix"): value for key, value in request["inputs"].items() if key.endswith("-prefix")}
    return produce(family, context, reference, prefixes)


def checked_expectation_bundle(reference, context):
    """Validate the complete pure handoff without granting native acceptance.

    @param reference Exact current merged expectation bundle path/hash.
    @param context Explicit consuming invocation sharing the source run.
    @return Checked bundle with five original protocols and ten configuration bindings.
    """
    path = selected_path(reference, context, "reports")
    bundle = json.loads(path.read_text(encoding="utf-8"))
    families = set(load_facts())
    # Source generation cannot acquire a native pass, another run or a new
    # family merely by presenting plausible binary bytes and a complete flag.
    if (bundle.get("kind") != "selected_merged_sprite_expectations" or bundle.get("schema_version") != 1
            or bundle.get("run_id") != context.run_id or bundle.get("native_loading_verified") is not False
            or bundle.get("publishes_source") is not False or set(bundle.get("families", {})) != families
            or bundle.get("adapter") != identity(Path(__file__), ROOT)
            or bundle.get("source_policy") != identity(FACTS, ROOT)):
        raise ValueError("merged expectation family/invocation/source policy changed")
    required = bundle.get("required_source_evidence")
    if not required:
        raise ValueError("merged expectations are missing required source evidence")
    proof = json.loads(selected_path(required, context, "evidence").read_text(encoding="utf-8"))
    if (proof.get("kind") != "selected_source_expectation_evidence" or proof.get("run_id") != context.run_id
            or proof.get("native_loading_verified") is not False or proof.get("source_result") != bundle["source_result"]
            or proof.get("candidate_manifest") != bundle["candidate_manifest"] or proof.get("source_policy") != bundle["source_policy"]
            or proof.get("families") != bundle["families"]):
        raise ValueError("required source evidence disagrees with the selected expectations")
    state = json.loads(selected_path(bundle["source_result"], context, "reports").read_text(encoding="utf-8"))
    candidate = json.loads(selected_path(bundle["candidate_manifest"], context, "reports").read_text(encoding="utf-8"))
    # The actual GRF is a separate input, never an expected-pixel supplier.
    # Its exact completed source witness stays attached across this phase.
    if (state.get("complete") is not True or state.get("status") != "verified" or state.get("run_id") != context.run_id
            or state["nodes"]["merged-art-candidates"]["outputs"]["manifest"] != bundle["candidate_manifest"]
            or candidate["candidate"] != bundle["actual_candidate"] or candidate["checksum"] != bundle["actual_checksum"]):
        raise ValueError("merged expectation actual candidate/source witness changed")
    selected_path(bundle["actual_candidate"], context, "data")
    selected_path(bundle["actual_checksum"], context, "data")
    for family, result in bundle["families"].items():
        actual = checked_payload(family, result["manifest"], context)
        if identity(actual, ROOT) != result["expected_payload"]:
            raise ValueError("merged source payload differs from its typed family report")
    from sprite_native_inputs import bind_expected_payload, observe_expected_payload
    if set(bundle.get("input_bindings", {})) != {"Debug", "RelWithDebInfo"}:
        raise ValueError("merged expectation configuration bindings are incomplete")
    # Each build configuration owns its own process binding even though these
    # independently verified original source bytes can be reused by both builds.
    for configuration, selected in bundle["input_bindings"].items():
        if set(selected) != families:
            raise ValueError("merged expectation configuration family coverage changed")
        for family, observed in selected.items():
            environment = bind_expected_payload(context, family, configuration, bundle["families"][family]["manifest"])
            if observe_expected_payload(context, environment, configuration) != observed:
                raise ValueError("merged expectation configuration/input binding changed")
    return bundle


def produce_from_candidates(candidate_reference, source_result):
    """Continue verified source packing through the existing expectation producers.

    @param candidate_reference Exact current Group52 candidate manifest identity.
    @param source_result Exact completed supplying recipe ledger identity, never a latest-run search.
    @return Current expectation bundle with separate source payload and actual GRF roles.
    """
    candidate_path = contained(ROOT / candidate_reference["path"], ROOT / "mlm/reviews")
    candidate = json.loads(candidate_path.read_text(encoding="utf-8"))
    run_id = identifier(candidate["run_id"])
    context = RunContext(ROOT, "multilayer-art", "merged-sprite-expectations", run_id)
    selected_path(candidate_reference, context, "reports")
    state_path = selected_path(source_result, context, "reports")
    state = json.loads(state_path.read_text(encoding="utf-8"))
    # Only the completed actual candidate graph may supply this phase. A copied
    # manifest or an incomplete source attempt cannot become native input proof.
    if (candidate.get("kind") != "selected_merged_art_candidates" or candidate.get("publishes_source") is not False
            or candidate.get("native_proof") is not False or state.get("complete") is not True
            or state.get("status") != "verified" or state.get("run_id") != run_id):
        raise ValueError("merged expectations require the completed explicit candidate source graph")
    if state["nodes"]["merged-art-candidates"]["outputs"]["manifest"] != candidate_reference:
        raise ValueError("candidate manifest differs from its completed source supplier")
    selected_path(candidate["candidate"], context, "data")
    selected_path(candidate["checksum"], context, "data")
    recipes = {row["id"]: row for row in load_catalogue(ROOT)["recipes"]}
    results = {}
    # Existing recipe edges order the actual prefix protocols. Reuse these
    # exact current packing reports instead of regenerating the source graph or
    # introducing another family catalogue, decoder or expectation algorithm.
    for name in recipe_order("ground-expected-payload", recipes):
        if not name.endswith("-expected-payload"):
            continue
        declaration = recipes[name]
        family = declaration["original_parameters"]["family"]
        packing_name = recipe_family(family) + "-derived-inputs"
        supplier = state["nodes"][packing_name]
        reference = candidate["suppliers"][recipe_family(family)]["manifest"]
        if supplier["status"] != "verified" or supplier["outputs"]["manifest"] != reference:
            raise ValueError("expectation packing supplier is incomplete or changed: " + packing_name)
        prefixes = {}
        for requirement in declaration["requires"]:
            if requirement["as"].endswith("-prefix"):
                prefix_family = recipes[requirement["recipe"]]["original_parameters"]["family"]
                prefixes[prefix_family] = results[prefix_family]["manifest"]
        current = RunContext(ROOT, declaration["feature"], declaration["scenario"], run_id)
        results[family] = produce(family, current, reference, prefixes)
        print(f"{family}: {results[family]['record_count']} independent source records", flush=True)
    if set(results) != set(load_facts()):
        raise ValueError("existing expectation graph omitted an original protocol family")
    from sprite_native_inputs import bind_expected_payload, observe_expected_payload
    bindings = {}
    # Identical source bytes support both configurations, but each actual
    # native process still receives its own exact configuration/family binding.
    for configuration in ("Debug", "RelWithDebInfo"):
        bindings[configuration] = {}
        for family, result in results.items():
            environment = bind_expected_payload(context, family, configuration, result["manifest"])
            bindings[configuration][family] = observe_expected_payload(context, environment, configuration)
    bundle = dict(_documentation=__doc__, schema_version=1, kind="selected_merged_sprite_expectations",
                  run_id=run_id, source_result=source_result, candidate_manifest=candidate_reference,
                  adapter=identity(Path(__file__), ROOT),
                  actual_candidate=candidate["candidate"], actual_checksum=candidate["checksum"], families=results,
                  input_bindings=bindings, source_policy=identity(FACTS, ROOT),
                  required_native_terminals="Not produced by source generation; native decoder/viewport owners must supply them.",
                  native_loading_verified=False, publishes_source=False)
    evidence = dict(_documentation=__doc__, kind="selected_source_expectation_evidence", run_id=run_id,
                    candidate_manifest=candidate_reference, source_result=source_result,
                    source_policy=bundle["source_policy"], families=results, native_loading_verified=False)
    context.evidence.mkdir(parents=True, exist_ok=True)
    proof = context.evidence / "source-generation.json"
    proof.write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8")
    bundle["required_source_evidence"] = identity(proof, ROOT)
    context.reports.mkdir(parents=True, exist_ok=True)
    output = context.reports / "expectations.json"
    output.write_text(json.dumps(bundle, indent=2) + "\n", encoding="utf-8")
    checked_expectation_bundle(identity(output, ROOT), context)
    return identity(output, ROOT)


def main():
    """Continue one explicit completed candidate run without reserving or publishing another source graph."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidates", type=Path, required=True, help="Exact current candidate manifest.")
    parser.add_argument("--source-result", type=Path, required=True, help="Exact completed supplying recipe ledger.")
    arguments = parser.parse_args()
    result = produce_from_candidates(identity(arguments.candidates.resolve(), ROOT), identity(arguments.source_result.resolve(), ROOT))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
